const clueFields = [
  "console",
  "release_year",
  "publisher",
  "developer",
  "total_sales",
];

const maxAttempts = 5;

export function normalize(value) {
  return value.trim().toLocaleLowerCase("pt-BR").replace(/\s+/g, " ");
}

function dailyIndex(date) {
  const utcDate = Date.UTC(date.getFullYear(), date.getMonth(), date.getDate());
  return Math.floor(utcDate / 86_400_000) % catalog.length;
}

function getDefinition(index) {
  return catalog[((index % catalog.length) + catalog.length) % catalog.length];
}

export function createGame(mode, round = 0, date = new Date()) {
  const definition = getDefinition(mode === "daily" ? dailyIndex(date) : round);
  return {
    id: crypto.randomUUID(),
    mode,
    image_url: definition.image_url,
    blur_percentage: 100,
    attempts: 0,
    max_attempts: maxAttempts,
    status: "active",
    correct: null,
    answer: null,
    targetTitle: definition.title,
    guesses: [],
  };
}

export function submitGameGuess(game, answer) {
  if (game.status !== "active") {
    throw new Error("Esta partida já foi encerrada.");
  }
  const cleanAnswer = answer.trim();
  if (!cleanAnswer) {
    throw new Error("Digite o nome de um jogo.");
  }

  const correct = normalize(cleanAnswer) === normalize(game.targetTitle);
  const attempts = game.attempts + 1;
  const status = correct
    ? "won"
    : attempts >= game.max_attempts
      ? "lost"
      : "active";
  return {
    ...game,
    attempts,
    status,
    correct,
    answer: status === "active" ? null : game.targetTitle,
    blur_percentage: correct ? 0 : Math.max(0, 100 - attempts * 20),
    guesses: [
      ...game.guesses,
      { id: game.attempts + 1, answer: cleanAnswer, correct },
    ],
  };
}

export function searchGames(query) {
  const normalizedQuery = normalize(query);
  if (normalizedQuery.length < 2) return [];
  return catalog
    .filter((game) => normalize(game.title).includes(normalizedQuery))
    .slice(0, 8)
    .map((game) => game.title);
}

export function createClueSession(round = 0, date = new Date()) {
  return {
    target: getDefinition(dailyIndex(date) + round),
    guesses: [],
    hints: [],
  };
}

function compareText(field, value, target) {
  return {
    field,
    value,
    result: normalize(value) === normalize(target) ? "correct" : "wrong",
    direction: null,
  };
}

function compareNumber(field, value, target, closeThreshold) {
  const difference = Math.abs(value - target);
  return {
    field,
    value,
    result:
      difference === 0
        ? "correct"
        : difference <= closeThreshold
          ? "close"
          : "wrong",
    direction: value < target ? "up" : value > target ? "down" : null,
  };
}

function compareSales(value, target) {
  const difference = target ? Math.abs(value - target) / target : 0;
  return {
    field: "total_sales",
    value,
    result:
      value === target ? "correct" : difference <= 0.2 ? "close" : "wrong",
    direction: value < target ? "up" : value > target ? "down" : null,
  };
}

export function searchClueGames(query) {
  return searchGames(query);
}

export function submitClueGuess(session, title) {
  if (session.guesses.some((guess) => guess.complete)) {
    throw new Error("Este jogo de pistas já foi concluído.");
  }
  const candidate = catalog.find(
    (game) => normalize(game.title) === normalize(title),
  );
  if (!candidate) {
    throw new Error("Escolha um jogo da lista de sugestões.");
  }

  const comparisons = [
    compareText("console", candidate.console, session.target.console),
    compareNumber(
      "release_year",
      candidate.release_year,
      session.target.release_year,
      2,
    ),
    compareText("publisher", candidate.publisher, session.target.publisher),
    compareText("developer", candidate.developer, session.target.developer),
    compareSales(candidate.total_sales, session.target.total_sales),
  ];
  const result = {
    id: session.guesses.length + 1,
    title: candidate.title,
    complete: comparisons.every(
      (comparison) => comparison.result === "correct",
    ),
    comparisons,
  };
  return { ...session, guesses: [result, ...session.guesses] };
}

export function revealNextHint(session) {
  if (session.guesses.some((guess) => guess.complete)) {
    throw new Error("Este jogo de pistas já foi concluído.");
  }
  const field = clueFields.find(
    (candidate) => !session.hints.some((hint) => hint.field === candidate),
  );
  if (!field) {
    throw new Error("Não há mais dicas disponíveis.");
  }
  const hint = { field, value: session.target[field] };
  return { session: { ...session, hints: [...session.hints, hint] }, hint };
}
